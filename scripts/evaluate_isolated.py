"""Explicit paid stage experiments; separate store, no production queue/cache or auto-resume."""
from __future__ import annotations
import argparse,hashlib,json,os,signal,subprocess,sys,time
from dataclasses import replace
from pathlib import Path
from math_agent.config import ROOT,Settings
from math_agent.storage import Store,write_json
MODES=('draw','source_raw','source_ocr','math_fast','math_low','draw_static')

def child(mode,out):
    from math_agent.pipeline import Runner
    from math_agent.provider import DeepSeek
    from math_agent.contracts import Source,check_source
    from math_agent.reference_flow import validate_math,assemble,patch_drawing,math_hash
    from math_agent.scene_tools import PreviewSpec
    from math_agent.rendering import RenderError
    for line in (ROOT/'.env').read_text().splitlines():
        if '=' in line and not line.startswith('#'):
            k,v=line.split('=',1);os.environ[k]=v
    settings=replace(Settings(),data_dir=out/'runtime',redis_url='',ocr_url='',effort='low',
        max_tokens=32000,source_max_tokens=8000,max_calls=12,max_repairs=1,reference_mode=False)
    class ExperimentalProvider(DeepSeek):
        def request(self,stage,history,tools=None,**kwargs):
            override=(mode=='math_low') if stage=='reference_math' else None
            kwargs["thinking_override"]=override
            return super().request(stage,history,tools,**kwargs)
    store=Store(settings.data_dir);job,directory=store.prepare();store.enqueue(job);store.claim()
    (out/'job-id.txt').write_text(job)
    case='20' if mode.startswith('source') else '48'
    files=[('question',ROOT/'fixtures'/f'{case}.png')]
    if mode.startswith('math'):files.append(('answer',ROOT/'fixtures'/'ref-48-answer-1.png'))
    images=[]
    for i,(role,p) in enumerate(files,1):
        data=p.read_bytes();name=f'I{i}.png';(directory/name).write_bytes(data)
        images.append({'id':f'I{i}','role':role,'file':name,'sha256':hashlib.sha256(data).hexdigest()})
    request={'text':'','images':images,'force':True,'ocr_evidence':json.loads((ROOT/'evaluation/isolation-v1/ocr-20.json').read_text()) if mode=='source_ocr' else []}
    write_json(directory/'request.json',request)
    write_json(out/'config.json',{'mode':mode,'model':settings.model,'effort':'low','max_tokens':32000,
        'max_calls':12,'ocr':'saved evidence, no OCR execution included' if mode=='source_ocr' else 'none',
        'math_thinking':mode=='math_low','image_hashes':[(i['role'],i['sha256']) for i in images],
        'note':'isolated stage experiment; never counts as end-to-end success'})
    r=Runner(settings,job,provider_factory=ExperimentalProvider);start=time.monotonic()
    result={'mode':mode,'status':'failed','end_to_end':False}
    try:
        if mode.startswith('source'):
            def validate(raw):
                s=Source.model_validate(raw);check_source(s,images);return s
            source=r.validated('source',{},validate)
            write_json(out/'source.json',source.model_dump())
            result.update(status='needs_input' if source.uncertainties else 'structured_output',uncertainties=source.uncertainties,
                note='first-pass only; semantic accuracy requires independent inspection')
        else:
            gold=json.loads((ROOT/'evaluation/isolation-v1/gold-48.json').read_text());source=Source.model_validate(gold['source'])
            r.save_ledger(source)
            if mode.startswith('math'):
                draft=r.validated('reference_math',{'source':source.model_dump(),'previous':None,'feedback':[]},lambda raw:validate_math(raw,source))
                write_json(out/'math.json',draft.model_dump())
                result.update(status='structured_output',note='contract-valid is not mathematics-correct')
            else:
                draft=validate_math(gold['math'],source);r.save_ledger(source,__import__('math_agent.contracts',fromlist=['Candidate']).Candidate(solutions=draft.solutions,spec={}))
                r.math_certificate={'sha256':math_hash(source,draft),'provenance':gold['provenance'],'review':{'type':'human-checked input fixture; not generated by math_review'}}
                policy='仅画每问已核实的答案位置，四个静态tab；不输出controls或新增滑块。仍须原生rotation/translation，图形关系不能写死坐标。' if mode=='draw_static' else '按既有规则自主选择展示方式'
                def drawing(raw):
                    value=PreviewSpec.model_validate(raw)
                    if mode=='draw_static' and any(t.controls for t in value.tabs):raise ValueError('本次隔离实验仅展示静态答案位置，请省略所有controls，不改变数学解答或原生几何关系')
                    return assemble(source,draft,value)
                candidate=r.validated('draw',{'source':source.model_dump(),'math':draft.model_dump(),'display_policy':policy},drawing)
                for attempt in range(2):
                    write_json(out/'candidate.json',candidate.model_dump())
                    try:
                        observation=r.observe(candidate)
                        review=r.review(source,candidate,observation,stage='graph_review')
                        write_json(out/f'review-{attempt}.json',review.model_dump())
                        feedback=[i.model_dump() for i in review.issues]
                        if review.verdict=='pass':result.update(status='stage_pass');break
                        if review.verdict=='needs_input' or any(i['stage']!='diagram' for i in feedback):
                            result.update(status='blocked',feedback=feedback);break
                    except RenderError as exc:
                        feedback=[{'stage':'diagram','target':'browser','detail':str(exc)}]
                    if attempt:result.update(status='failed',feedback=feedback);break
                    previous={'tabs':[{k:t[k] for k in ('board','controls') if k in t} for t in candidate.spec['tabs']]}
                    def patch(raw):
                        value=patch_drawing(source,draft,candidate,raw)
                        if mode=='draw_static' and any(t.get('controls') for t in value.spec['tabs']):raise ValueError('静态答案位置实验不得新增controls')
                        return value
                    candidate=r.validated('draw_patch',{'source':source.model_dump(),'math':draft.model_dump(),'previous_drawing':previous,'feedback':feedback,'display_policy':policy},patch)
                    if candidate.solutions!=draft.solutions:raise ValueError('图形实验不得改变核实过的数学')
    except Exception as exc:
        result.update(status='failed',error=str(exc)[:3000],error_type=type(exc).__name__)
    finally:
        r.provider.close();result['seconds']=round(time.monotonic()-start,3);result['returned_calls']=len([x for x in r.records if x['kind']=='model'])
        write_json(out/'result.json',result)
    print(json.dumps(result,ensure_ascii=False),flush=True)

def run(mode,out,seconds):
    out.mkdir(parents=True,exist_ok=False)
    with (out/'run.log').open('w') as log:
        p=subprocess.Popen([sys.executable,__file__,'--mode',mode,'--out',str(out),'--child'],stdout=log,stderr=log,start_new_session=True)
        try:p.wait(timeout=seconds)
        except subprocess.TimeoutExpired:
            os.killpg(p.pid,signal.SIGTERM)
            try:p.wait(timeout=3)
            except subprocess.TimeoutExpired:os.killpg(p.pid,signal.SIGKILL);p.wait()
            write_json(out/'result.json',{'mode':mode,'status':'timeout','seconds':seconds,'end_to_end':False,'note':'pending requests may still be billed; no replay'})
        finally:
            try:os.killpg(p.pid,signal.SIGKILL)
            except ProcessLookupError:pass
    if not (out/'result.json').exists():write_json(out/'result.json',{'mode':mode,'status':'process_failed','exit_code':p.returncode,'end_to_end':False})
    print(mode,(out/'result.json').read_text(),flush=True)

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--mode',choices=(*MODES,'all'),required=True)
    parser.add_argument('--out',type=Path,required=True);parser.add_argument('--child',action='store_true')
    args=parser.parse_args();out=args.out.resolve()
    if args.child:child(args.mode,out)
    elif args.mode=='all':
        out.mkdir(parents=True,exist_ok=False)
        for mode in MODES:run(mode,out/mode,90 if mode.startswith('source') else 240)
    else:run(args.mode,out,90 if args.mode.startswith('source') else 240)
